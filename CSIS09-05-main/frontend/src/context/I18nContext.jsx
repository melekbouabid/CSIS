function getValue(obj, path) {
  return path.split(".").reduce((acc, part) => (acc && acc[part] !== undefined ? acc[part] : undefined), obj);
}

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem("ddd_lang") || "en");

  useEffect(() => {
    localStorage.setItem("ddd_lang", lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  const value = useMemo(() => {
    const t = (key, params = {}) => {
      const fromCurrent = getValue(messages[lang], key);
      const fallback = getValue(messages.en, key);
      const raw = fromCurrent ?? fallback ?? key;
      return Object.entries(params).reduce((txt, [k, v]) => txt.replace(`{{${k}}}`, String(v)), raw);
    };

    return { lang, setLang, t };
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
